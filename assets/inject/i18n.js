  function getCodexPlusLang() {
    try {
      const stored = localStorage.getItem(CODEX_PLUS_LANG_KEY);
      if (stored === "en" || stored === "zh") return stored;
    } catch (_) {}
    if (window.__CODEX_PLUS_UI_LANG__ === "en" || window.__CODEX_PLUS_UI_LANG__ === "zh") {
      return window.__CODEX_PLUS_UI_LANG__;
    }
    try {
      const settings = JSON.parse(localStorage.getItem("codexPlusSettings") || "{}");
      if (settings.uiLanguage === "en" || settings.uiLanguage === "zh") return settings.uiLanguage;
    } catch (_) {}
    return (navigator.language || "").toLowerCase().startsWith("zh") ? "zh" : "en";
  }

  function setCodexPlusLang(lang) {
    if (lang !== "en" && lang !== "zh") return;
    try {
      localStorage.setItem(CODEX_PLUS_LANG_KEY, lang);
    } catch (_) {}
    try {
      const settings = JSON.parse(localStorage.getItem("codexPlusSettings") || "{}");
      localStorage.setItem("codexPlusSettings", JSON.stringify({ ...settings, uiLanguage: lang }));
    } catch (_) {}
  }

  function t(key, vars) {
    const lang = getCodexPlusLang();
    let text = MESSAGES[lang]?.[key] ?? MESSAGES.en[key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.replaceAll(`{{${name}}}`, String(value));
      }
    }
    return text;
  }

  window.__codexPlusT = t;
  window.__codexPlusGetLang = getCodexPlusLang;
  window.__codexPlusSetLang = setCodexPlusLang;
