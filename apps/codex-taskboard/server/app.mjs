function parseCodexThreadSync(body) {
  assertPlainObject(body);
  assertAllowedKeys(body, new Set(["projectId", "visibleThreadIds"]));
  const projectId = validateProjectId(body.projectId);
  if (!Array.isArray(body.visibleThreadIds) || body.visibleThreadIds.length > 1000) {
    throw new ApiError(400, "INVALID_FIELD", "'visibleThreadIds' must be an array of at most 1000 items");
  }
  const seen = new Set();
  const visibleThreadIds = [];
  for (const value of body.visibleThreadIds) {
    if (typeof value !== "string") {
      throw new ApiError(400, "INVALID_FIELD", "'visibleThreadIds' must contain strings");
    }
    const threadId = normalizeCodexThreadId(value);
    if (!threadId || threadId.startsWith("client-new-thread:") || seen.has(threadId)) continue;
    seen.add(threadId);
    visibleThreadIds.push(threadId);
  }
  return { projectId, visibleThreadIds };
}

